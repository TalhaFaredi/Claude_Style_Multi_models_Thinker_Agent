// Demo fixtures never exceed the minimum UI threshold ($0.10); lower only the persisted
// audit-browser threshold so the same production guardrail's over-limit path can be exercised.
await page.evaluate(()=>{const settings=JSON.parse(localStorage.getItem('mma-settings'));settings.state.askLimit=0.05;localStorage.setItem('mma-settings',JSON.stringify(settings));});
await page.reload({waitUntil:'networkidle'});
await page.getByRole('button',{name:'Attach a file'}).click();
await dialog.getByRole('button',{name:/Q3_Report.pdf/}).click();
record('F8: over-limit file amber warning',await dialog.getByText(/Over your.*ask-me limit/).isVisible(),true);
record('F8: over-limit file offers free text-only choice',await dialog.getByRole('button',{name:'Text only (free)',exact:true}).isVisible(),true);
await dialog.getByRole('button',{name:/Read file/}).click();
await page.locator('.fchip').getByText('Ready',{exact:true}).waitFor();
await page.getByRole('button',{name:'Set up this mode'}).click();
await dialog.getByRole('button',{name:'Mistral Large',exact:true}).click();
record('F5: nonvision model disabled after charts attached',await dialog.getByRole('button',{name:/DeepSeek \(latest\)/}).isDisabled(),true);
await dialog.getByRole('button',{name:'Done',exact:true}).click();
await close();
await settings();
await page.getByRole('tab',{name:'Memory',exact:true}).click();
await dialog.getByRole('switch',{name:'Remember facts across chats'}).click();
await page.getByRole('tab',{name:'Data and safety'}).click();
await dialog.getByRole('switch',{name:/Temporary chat/}).click();
await dialog.getByRole('button',{name:'Reset everything to safe defaults'}).click();
record('F12: reset clears Temporary chat',await dialog.getByRole('switch',{name:/Temporary chat/}).getAttribute('aria-checked'),'false');
await page.getByRole('tab',{name:'Memory',exact:true}).click();
record('F12: reset restores Long-term memory',await dialog.getByRole('switch',{name:'Remember facts across chats'}).getAttribute('aria-checked'),'true');
await close();
await mode('Thinker').click();
await page.getByRole('button',{name:'Set up this mode'}).click();
