const settings=async()=>page.getByRole('button',{name:'Settings, memory, data',exact:true}).click();
await mode('Simple').click();
await page.getByRole('button',{name:'Set up this mode'}).click();
const dialog=page.getByRole('dialog');
for (const name of ['Web search','Code']) {const b=dialog.getByRole('button',{name,exact:true}); if(await b.getAttribute('aria-pressed')==='true')await b.click();}
record('File reader remains on',await dialog.getByRole('button',{name:'Files',exact:true}).getAttribute('aria-pressed'),'true');
await dialog.getByRole('button',{name:'Claude Sonnet 5.5',exact:true}).click();
record('F4: tool-incapable model disabled with only File reader enabled',await dialog.getByRole('button',{name:/Llama 3\.3/}).isDisabled(),true);
await dialog.getByRole('button',{name:/Mistral Large/}).click();
await dialog.getByRole('button',{name:'Done',exact:true}).click();
record('F6: non-thinking model sets thinking Off',await dialog.getByRole('group',{name:'Thinking level'}).getByRole('button',{name:'Off',exact:true}).getAttribute('aria-pressed'),'true');
